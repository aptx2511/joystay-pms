import { NextResponse } from "next/server";
import { prisma } from "@/lib/prisma";
import {
  DAY, DEFAULT_WINDOW, LOOKAHEAD_DAYS, buildChecklist, generateCleaningTasks, loadTasks, newToken,
  roomBoard, taskLink, vnToday,
} from "@/lib/housekeeping";

export const dynamic = "force-dynamic";

// GET /api/housekeeping?days=14  → lịch dọn (hôm qua → +days), bảng trạng thái phòng, danh sách lao công
export async function GET(request: Request) {
  try {
    const { searchParams } = new URL(request.url);
    const days = Math.min(Number(searchParams.get("days")) || LOOKAHEAD_DAYS, 31);
    const gen = await generateCleaningTasks(days);
    const today = vnToday();
    const [tasks, board, cleaners, rooms] = await Promise.all([
      loadTasks(new Date(today.getTime() - DAY), new Date(today.getTime() + days * DAY)),
      roomBoard(),
      prisma.cleaner.findMany({ orderBy: [{ active: "desc" }, { createdAt: "asc" }] }),
      prisma.room.findMany({ orderBy: { sortOrder: "asc" }, select: { id: true, name: true, roomNumber: true, size: true } }),
    ]);
    return NextResponse.json({
      generated: gen,
      today: today.toISOString().slice(0, 10),
      tasks: tasks.map((t) => ({ ...t, link: taskLink(t) })),
      board,
      cleaners,
      rooms,
    });
  } catch (error) {
    console.error("[GET /api/housekeeping]", error);
    return NextResponse.json({ error: "Không tải được lịch dọn" }, { status: 500 });
  }
}

// POST /api/housekeeping  { roomId, date: "YYYY-MM-DD", type: "MIDSTAY"|"DEEP"|"TURNOVER", note?, cleanerId? }
export async function POST(request: Request) {
  try {
    const { roomId, date, type = "MIDSTAY", note, cleanerId } = (await request.json()) as {
      roomId?: string; date?: string; type?: string; note?: string; cleanerId?: string;
    };
    if (!roomId || !date || !/^\d{4}-\d{2}-\d{2}$/.test(date)) {
      return NextResponse.json({ error: "Cần chọn phòng và ngày" }, { status: 400 });
    }
    if (!["MIDSTAY", "DEEP", "TURNOVER"].includes(type)) {
      return NextResponse.json({ error: "Loại việc không hợp lệ" }, { status: 400 });
    }
    const room = await prisma.room.findUnique({ where: { id: roomId } });
    if (!room) return NextResponse.json({ error: "Không thấy phòng" }, { status: 404 });

    const day = new Date(`${date}T00:00:00.000Z`);
    const exists = await prisma.cleaningTask.findUnique({ where: { roomId_date_type: { roomId, date: day, type } } });
    if (exists) return NextResponse.json({ error: "Phòng này đã có việc cùng loại trong ngày đó" }, { status: 409 });

    const task = await prisma.cleaningTask.create({
      data: {
        roomId, date: day, type, note: note || null,
        cleanerId: cleanerId || null,
        status: cleanerId ? "ASSIGNED" : "TODO",
        token: newToken(),
        autoGenerated: false,
        checklist: buildChecklist(room) as unknown as object,
        windowStart: DEFAULT_WINDOW.start,
        windowEnd: DEFAULT_WINDOW.end,
      },
      include: { room: true, cleaner: true },
    });
    return NextResponse.json({ ...task, link: taskLink(task) }, { status: 201 });
  } catch (error) {
    console.error("[POST /api/housekeeping]", error);
    return NextResponse.json({ error: "Không tạo được việc dọn" }, { status: 500 });
  }
}
